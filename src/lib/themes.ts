import type { ITheme } from "@xterm/xterm";
import type { Theme } from "./theme";

/** One theme colors the whole app: the window (with its title bar, sidebar,
 * tabs, panels and menus), the code in the editor and the text in terminals.
 * Each has a dark version, and most a light one, following the app's mode. Default is
 * Lookout's own window colors with One Dark Pro text; the others take their
 * window colors from their VS Code themes. Text colors come from the
 * iTerm2-Color-Schemes project (terminal) and the tm-themes package (editor). */

/** Editor syntax colors. */
export interface SyntaxColors {
  keyword: string;
  string: string;
  number: string;
  comment: string;
  function: string;
  type: string;
  property: string;
  tag: string;
  variable: string;
  punctuation: string;
  selection?: string;
}

/** A theme's window colors: its side bar for the title bar, sidebar and
 * terminals, its editor background for files, and its text. */
export interface WindowColors {
  chrome: string;
  bg: string;
  fg: string;
}

export interface ThemeVersion {
  /** Null: Lookout's own colors from styles.css. */
  window: WindowColors | null;
  terminal: ITheme;
  syntax: SyntaxColors;
}

export interface ColorTheme {
  id: string;
  label: string;
  dark: ThemeVersion;
  /** Null for a theme with no light version; light mode then uses Default. */
  light: ThemeVersion | null;
}

