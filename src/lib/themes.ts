export const COLOR_THEME_KEY = "lookout.color-theme";

export function savedColorTheme(): string {
  const saved = localStorage.getItem(COLOR_THEME_KEY);
  return THEMES.some((t) => t.id === saved) ? saved! : "default";
}

/** Lookout's own window colors (--chrome, --bg and --fg in styles.css). */
export const DEFAULT_WINDOW: Record<Theme, WindowColors> = {
  dark: { chrome: "#080808", bg: "#101010", fg: "#cccccc" },
  light: { chrome: "#f7f7f9", bg: "#ffffff", fg: "#1d1d1f" },
};

/** The version of a theme for the mode. A theme without a light version uses Default's. */
export function themeVersion(id: string, mode: Theme): ThemeVersion {
  const theme = THEMES.find((t) => t.id === id) ?? THEMES[0];
  return mode === "light" ? (theme.light ?? THEMES[0].light!) : theme.dark;
}

/** Terminal colors. The terminal is drawn transparent over the window's
 * --chrome color, since macOS shows canvas colors slightly differently from
 * page colors; the window color is for text under the block cursor. */
export function terminalColors(id: string, mode: Theme): ITheme {
  const version = themeVersion(id, mode);
  return { ...version.terminal, background: "rgba(0, 0, 0, 0)", cursorAccent: (version.window ?? DEFAULT_WINDOW[mode]).chrome };
}

type Rgb = [number, number, number];

function rgb(hex: string): Rgb {
  const h = hex.replace("#", "");
  const full = h.length === 3 ? [...h].map((c) => c + c).join("") : h.slice(0, 6);
  return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16)) as Rgb;
}

const toHex = (c: Rgb) => "#" + c.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");

/** `a` with `t` (0 to 1) of `b` mixed in. */
const mix = (a: string, b: string, t: number) => toHex(rgb(a).map((v, i) => v + (rgb(b)[i] - v) * t) as Rgb);

const alpha = (c: string, a: number) => `rgba(${rgb(c).join(", ")}, ${a})`;

/** The CSS variables a theme sets on the page, over the ones in styles.css. */
export function windowTokens(w: WindowColors, mode: Theme): Record<string, string> {
  const dark = mode === "dark";
  const { chrome, bg, fg } = w;
  return {
    "--chrome": chrome,
    "--bg": bg,
    "--bg-subtle": mix(chrome, "#000000", dark ? 0.25 : 0.02),
    "--bg-muted": dark ? mix(bg, fg, 0.06) : mix(bg, "#ffffff", 0.6),
    "--fg": fg,
    "--fg-strong": dark ? mix(fg, "#ffffff", 0.35) : mix(fg, "#000000", 0.45),
    "--fg-2": mix(fg, bg, 0.28),
    "--fg-3": mix(fg, bg, 0.55),
    "--border": alpha(fg, 0.08),
    "--border-strong": mix(bg, fg, 0.16),
    "--hover": alpha(fg, 0.07),
    "--press": alpha(fg, 0.11),
    "--sel": alpha(fg, 0.07),
    "--sel-focus": alpha(fg, 0.13),
    "--dots": alpha(fg, 0.08),
    "--scrollbar": alpha(fg, 0.2),
    "--scrollbar-hover": alpha(fg, 0.32),
    "--input-border": mix(bg, fg, 0.12),
    "--button-hover": mix(bg, fg, 0.09),
    "--menu-hover": alpha(fg, 0.16),
    "--badge": mix(bg, fg, 0.25),
    "--switch-thumb": dark ? mix(bg, fg, 0.2) : "#ffffff",
    "--group-bg": alpha(fg, 0.05),
    "--group-ring": `inset 0 0 0 1px ${alpha(fg, 0.07)}`,
    "--raised": dark ? alpha(fg, 0.11) : mix(bg, "#ffffff", 0.7),
    "--editor-active-line": alpha(fg, 0.04),
  };
}

/** The variables windowTokens sets, to take off again for Default. */
export const WINDOW_TOKENS = Object.keys(windowTokens(DEFAULT_WINDOW.dark, "dark"));

/** Puts a theme's colors on the page: its window colors, or Lookout's own for
 * Default, and the editor's syntax colors. */
export function applyTheme(id: string, mode: Theme) {
  const version = themeVersion(id, mode);
  const style = document.documentElement.style;
  const tokens = version.window ? windowTokens(version.window, mode) : null;
  for (const name of WINDOW_TOKENS) {
    if (tokens) style.setProperty(name, tokens[name]);
    else style.removeProperty(name);
  }
  const { selection, ...syntax } = version.syntax;
  for (const [key, value] of Object.entries(syntax)) style.setProperty(`--syn-${key}`, value);
  if (selection) style.setProperty("--editor-selection", selection);
  else style.removeProperty("--editor-selection");
}
