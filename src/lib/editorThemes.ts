export const EDITOR_THEME_KEY = "lookout.editor-theme";

export function savedEditorTheme(): string {
  const saved = localStorage.getItem(EDITOR_THEME_KEY);
  return EDITOR_THEMES.some((t) => t.id === saved) ? saved! : "one-dark";
}

export function editorColors(id: string, mode: Theme): SyntaxColors {
  const theme = EDITOR_THEMES.find((t) => t.id === id) ?? EDITOR_THEMES[0];
  // Text made for a dark background is unreadable on white, so a theme without
  // a light version uses the default's light colors.
  return mode === "light"
    ? (theme.light ?? EDITOR_THEMES[0].light!)
    : theme.dark;
}
