export const TERMINAL_THEME_KEY = "lookout.terminal-theme";

export function savedTerminalTheme(): string {
  const saved = localStorage.getItem(TERMINAL_THEME_KEY);
  return TERMINAL_THEMES.some((t) => t.id === saved) ? saved! : "one-dark";
}

/** The top bar's color (--chrome in styles.css). The terminal itself is drawn
 * transparent over it, since macOS shows canvas colors slightly differently
 * from page colors; this copy is for text under the block cursor. */
const BACKGROUND: Record<Theme, string> = { dark: "#080808", light: "#f7f7f9" };

export function terminalColors(id: string, mode: Theme): ITheme {
  const theme = TERMINAL_THEMES.find((t) => t.id === id) ?? TERMINAL_THEMES[0];
  // Text made for a dark background is unreadable on white, so a theme without
  // a light version uses the default's light colors.
  const colors = mode === "light" ? (theme.light ?? TERMINAL_THEMES[0].light!) : theme.dark;
  return { ...colors, background: "rgba(0, 0, 0, 0)", cursorAccent: BACKGROUND[mode] };
}
